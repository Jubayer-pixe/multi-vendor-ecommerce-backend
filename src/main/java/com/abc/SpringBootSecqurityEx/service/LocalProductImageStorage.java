package com.abc.SpringBootSecqurityEx.service;

import jakarta.annotation.PostConstruct;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Component;
import org.springframework.web.server.ResponseStatusException;

import javax.imageio.ImageIO;
import javax.imageio.ImageReader;
import javax.imageio.stream.ImageInputStream;
import java.awt.image.BufferedImage;
import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.nio.file.StandardOpenOption;
import java.nio.file.LinkOption;
import java.util.Iterator;
import java.util.Locale;
import java.util.UUID;

/** Local filesystem image storage. All names are generated by this class. */
@Component
public class LocalProductImageStorage implements ProductImageStorage {
    private static final String STAGING_PREFIX = ".upload-";

    private final Path configuredDirectory;
    private final long maxFileBytes;
    private final int maxWidth;
    private final int maxHeight;
    private final long maxPixels;
    private Path root;
    private Path staging;

    public LocalProductImageStorage(
            @Value("${app.product-images.storage-directory:${user.home}/.springbootsecurity/product-images}") String directory,
            @Value("${app.product-images.max-file-size-bytes:5242880}") long maxFileBytes,
            @Value("${app.product-images.max-width:4096}") int maxWidth,
            @Value("${app.product-images.max-height:4096}") int maxHeight,
            @Value("${app.product-images.max-pixels:12000000}") long maxPixels) {
        this.configuredDirectory = Path.of(directory).toAbsolutePath().normalize();
        this.maxFileBytes = maxFileBytes;
        this.maxWidth = maxWidth;
        this.maxHeight = maxHeight;
        this.maxPixels = maxPixels;
        if (maxFileBytes <= 0 || maxWidth <= 0 || maxHeight <= 0 || maxPixels <= 0) {
            throw new IllegalArgumentException("Product image limits must be positive");
        }
    }

    @PostConstruct
    void initialize() {
        try {
            Files.createDirectories(configuredDirectory);
            root = configuredDirectory.toRealPath();
            ensureOutsideClasspathWebRoots();
            staging = root.resolve(".staging");
            Files.createDirectories(staging);
            staging = staging.toRealPath();
            if (!staging.startsWith(root)) {
                throw new IllegalStateException("Image staging directory is outside configured storage");
            }
        } catch (IOException exception) {
            throw new IllegalStateException("Product image storage is unavailable", exception);
        }
    }

    @Override
    public StagedImage stage(InputStream input) throws IOException {
        requireInitialized();
        String stagingKey = UUID.randomUUID().toString();
        Path staged = stagedPath(stagingKey);
        if (!staged.startsWith(staging)) {
            throw invalidImage();
        }

        long copied = 0;
        boolean created = false;
        try {
            var output = Files.newOutputStream(staged, StandardOpenOption.CREATE_NEW, StandardOpenOption.WRITE);
            created = true;
            try (output) {
            byte[] buffer = new byte[8192];
            int read;
            while ((read = input.read(buffer)) != -1) {
                copied += read;
                if (copied > maxFileBytes) {
                    throw new ResponseStatusException(HttpStatus.PAYLOAD_TOO_LARGE, "Image exceeds the configured size limit");
                }
                output.write(buffer, 0, read);
            }
            }
        } catch (IOException | RuntimeException exception) {
            if (created) Files.deleteIfExists(staged);
            throw exception;
        }

        try {
            ImageMetadata metadata = inspectImage(staged);
            String extension = metadata.contentType.equals("image/jpeg") ? "jpg" : "png";
            String storageKey = UUID.randomUUID() + "." + extension;
            return new StagedImage(stagingKey, storageKey, metadata.contentType, copied,
                    metadata.width, metadata.height);
        } catch (IOException | RuntimeException exception) {
            Files.deleteIfExists(staged);
            throw exception;
        }
    }

    private ImageMetadata inspectImage(Path file) throws IOException {
        String signatureType = sniffType(file);
        try (ImageInputStream imageInput = ImageIO.createImageInputStream(file.toFile())) {
            if (imageInput == null) throw invalidImage();
            Iterator<ImageReader> readers = ImageIO.getImageReaders(imageInput);
            if (!readers.hasNext()) throw invalidImage();
            ImageReader reader = readers.next();
            try {
                reader.setInput(imageInput, true, true);
                int width = reader.getWidth(0);
                int height = reader.getHeight(0);
                if (width <= 0 || height <= 0 || width > maxWidth || height > maxHeight
                        || (long) width * height > maxPixels) {
                    throw new ResponseStatusException(HttpStatus.BAD_REQUEST,
                            "Image dimensions exceed the configured limit");
                }
                BufferedImage decoded = reader.read(0);
                if (decoded == null || decoded.getWidth() != width || decoded.getHeight() != height) {
                    throw invalidImage();
                }
                String readerType = reader.getFormatName().toLowerCase(Locale.ROOT);
                String decodedType = readerType.equals("jpeg") || readerType.equals("jpg") ? "image/jpeg"
                        : readerType.equals("png") ? "image/png" : null;
                if (!signatureType.equals(decodedType)) throw invalidImage();
                return new ImageMetadata(decodedType, width, height);
            } finally {
                reader.dispose();
            }
        }
    }

    private String sniffType(Path file) throws IOException {
        try (InputStream input = Files.newInputStream(file)) {
            byte[] header = input.readNBytes(8);
            int count = header.length;
            if (count >= 3 && (header[0] & 0xff) == 0xff && (header[1] & 0xff) == 0xd8
                    && (header[2] & 0xff) == 0xff) return "image/jpeg";
            if (count == 8 && (header[0] & 0xff) == 0x89 && header[1] == 'P' && header[2] == 'N'
                    && header[3] == 'G' && header[4] == 0x0d && header[5] == 0x0a
                    && header[6] == 0x1a && header[7] == 0x0a) return "image/png";
        }
        throw invalidImage();
    }

    @Override
    public void promote(StagedImage image) throws IOException {
        Path source = stagedPath(image.stagingKey());
        Path target = storagePath(image.storageKey());
        if (Files.exists(target, LinkOption.NOFOLLOW_LINKS)) {
            throw new IOException("Generated image key already exists");
        }
        try {
            Files.move(source, target, StandardCopyOption.ATOMIC_MOVE);
        } catch (java.nio.file.AtomicMoveNotSupportedException exception) {
            Files.move(source, target);
        }
    }

    @Override
    public InputStream open(String storageKey) throws IOException {
        Path path = storagePath(storageKey);
        rejectSymbolicLink(path);
        return Files.newInputStream(path);
    }

    @Override
    public StoredImage inspect(String storageKey) throws IOException {
        Path path = storagePath(storageKey);
        rejectSymbolicLink(path);
        if (!Files.isRegularFile(path)) throw new IOException("Stored image is missing");
        String contentType = sniffType(path);
        String expectedType = storageKey.endsWith(".jpg") ? "image/jpeg" : "image/png";
        if (!contentType.equals(expectedType)) throw new IOException("Stored image content is invalid");
        return new StoredImage(contentType, Files.size(path), 0, 0);
    }

    @Override
    public void delete(String storageKey) throws IOException {
        Path path = storagePath(storageKey);
        rejectSymbolicLink(path);
        Files.deleteIfExists(path);
    }

    @Override
    public void discard(StagedImage image) throws IOException {
        Files.deleteIfExists(stagedPath(image.stagingKey()));
    }

    private Path storagePath(String key) throws IOException {
        requireInitialized();
        if (key == null || !key.matches("[0-9a-fA-F-]{36}\\.(jpg|png)")) {
            throw new IOException("Invalid image storage key");
        }
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root) || path.getParent() == null || !path.getParent().equals(root)) {
            throw new IOException("Invalid image storage key");
        }
        return path;
    }

    private Path stagedPath(String key) throws IOException {
        requireInitialized();
        if (key == null || !key.matches("[0-9a-fA-F-]{36}")) throw new IOException("Invalid staging key");
        Path path = staging.resolve(STAGING_PREFIX + key).normalize();
        if (!path.startsWith(staging) || !path.getParent().equals(staging)) throw new IOException("Invalid staging key");
        return path;
    }

    private void rejectSymbolicLink(Path path) throws IOException {
        if (Files.isSymbolicLink(path)) throw new IOException("Invalid image file");
    }

    private void ensureOutsideClasspathWebRoots() throws IOException {
        for (String resourceRoot : new String[]{"static/", "public/", "META-INF/resources/"}) {
            var resource = LocalProductImageStorage.class.getClassLoader().getResource(resourceRoot);
            if (resource != null && "file".equalsIgnoreCase(resource.getProtocol())) {
                Path publicRoot;
                try {
                    publicRoot = Path.of(resource.toURI()).toRealPath();
                } catch (Exception exception) {
                    throw new IOException("Unable to validate private image storage location", exception);
                }
                if (root.startsWith(publicRoot)) {
                    throw new IllegalStateException("Product image storage must be outside classpath web roots");
                }
            }
        }
    }

    private void requireInitialized() throws IOException {
        if (root == null || staging == null) throw new IOException("Image storage is unavailable");
    }

    private ResponseStatusException invalidImage() {
        return new ResponseStatusException(HttpStatus.BAD_REQUEST, "Only valid JPEG and PNG images are accepted");
    }

    private record ImageMetadata(String contentType, int width, int height) { }
}
