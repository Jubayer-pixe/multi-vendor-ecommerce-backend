-- Persists completed checkout idempotency keys and the original response.
-- Apply after V20261104_01__invoice_tables.sql. Do not delete rows while their keys
-- are expected to remain replay-safe.
CREATE TABLE checkout_idempotency (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    idempotency_key VARCHAR(36) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    order_id BIGINT NOT NULL,
    response_json TEXT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_checkout_idempotency_customer_key UNIQUE (customer_id, idempotency_key),
    CONSTRAINT uk_checkout_idempotency_order_id UNIQUE (order_id),
    CONSTRAINT fk_checkout_idempotency_customer FOREIGN KEY (customer_id)
        REFERENCES customers (id) ON DELETE RESTRICT,
    CONSTRAINT fk_checkout_idempotency_order FOREIGN KEY (order_id)
        REFERENCES orders (id) ON DELETE RESTRICT
);
