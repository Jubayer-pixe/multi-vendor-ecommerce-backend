-- Manual PostgreSQL setup for invoice snapshots.
-- Apply once before deploying the invoice feature; this project has no Flyway/Liquibase runner.
CREATE TABLE invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    invoice_number VARCHAR(80) NOT NULL,
    customer_name VARCHAR(200) NOT NULL,
    customer_phone VARCHAR(40),
    delivery_address VARCHAR(1000) NOT NULL,
    payment_method VARCHAR(40) NOT NULL,
    payment_status VARCHAR(40) NOT NULL,
    order_status VARCHAR(40) NOT NULL,
    subtotal NUMERIC(19, 2) NOT NULL,
    discount NUMERIC(19, 2) NOT NULL,
    shipping_fee NUMERIC(19, 2) NOT NULL,
    grand_total NUMERIC(19, 2) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_invoices_order_id UNIQUE (order_id),
    CONSTRAINT uk_invoices_invoice_number UNIQUE (invoice_number),
    CONSTRAINT fk_invoices_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT
);

CREATE TABLE invoice_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL,
    item_name VARCHAR(300) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(19, 2) NOT NULL,
    line_total NUMERIC(19, 2) NOT NULL,
    CONSTRAINT fk_invoice_items_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE
);

CREATE INDEX ix_invoice_items_invoice_id ON invoice_items (invoice_id);
